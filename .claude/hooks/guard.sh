#!/bin/bash
# PreToolUse guardrails for the rules in CLAUDE.md that a tool call can break.
# Denies with a reason Claude sees; anything else passes through untouched.
set -uo pipefail

input="$(cat)"
tool="$(jq -r '.tool_name // empty' <<<"$input")"
root="${CLAUDE_PROJECT_DIR:-$(pwd)}"

deny() {
  jq -n --arg r "$1" '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: "deny", permissionDecisionReason: $r}}'
  exit 0
}

case "$tool" in
  Edit|Write|MultiEdit|NotebookEdit)
    path="$(jq -r '.tool_input.file_path // .tool_input.notebook_path // empty' <<<"$input")"
    rel="${path#"$root"/}"
    case "$rel" in
      backend/internal/*/*db/*.go)
        deny "$rel is generated by sqlc. Edit backend/queries/*.sql (or a new migration) and run 'make generate' (sqlc $(awk '$1=="sqlc"{print $2}' "$root/.tool-versions"))." ;;
      frontend/src/api/schema.d.ts)
        deny "$rel is generated from api/openapi.yaml. Edit the spec and run 'cd frontend && npm run gen:api'." ;;
      envs/prod.env|backups/*)
        deny "$rel may hold real credentials or production data; it is never read or edited by Claude." ;;
      backend/migrations/*.sql)
        if git -C "$root" cat-file -e "HEAD:$rel" 2>/dev/null; then
          deny "$rel is already committed (applied migrations are immutable). Add a new goose migration instead."
        fi ;;
    esac
    ;;
  Bash)
    cmd="$(jq -r '.tool_input.command // empty' <<<"$input")"
    # Only the command itself is checked, not heredoc bodies (commit messages, file contents).
    cmd="${cmd%%<<*}"
    if grep -Eq 'git[^|;&]*\bpush\b[^|;&]*(--force|--force-with-lease|[[:space:]]-f\b)' <<<"$cmd"; then
      deny "Force pushes are not allowed (main is protected; never rewrite pushed history). Push a new commit instead."
    fi
    if grep -Eq 'git[^|;&]*\bpush\b[^|;&]*[[:space:]](origin[[:space:]]+)?(HEAD:)?main\b' <<<"$cmd"; then
      deny "Never push to main: changes reach main only through a reviewed PR that Ed merges."
    fi
    if grep -Eq -- '--no-verify\b|\bgit[^|;&]*\brebase[^|;&]*[[:space:]]-i\b' <<<"$cmd"; then
      deny "--no-verify and interactive rebase are not allowed in this repo."
    fi
    if grep -Eq '\bpkill[[:space:]]+(-[a-zA-Z]*f|--full)' <<<"$cmd"; then
      deny "pkill -f can match and kill this shell. Stop a server by port instead: fuser -k <port>/tcp."
    fi
    if grep -Eq 'prettier[^|;&]*--write' <<<"$cmd" && grep -Eq '(^|[[:space:]/])e2e(/|[[:space:]]|$)' <<<"$cmd"; then
      deny "e2e/ has no Prettier config: running Prettier there rewrites files with the wrong style. Format only frontend/ (its config), and keep e2e/ edits hand-formatted."
    fi
    ;;
esac
exit 0
